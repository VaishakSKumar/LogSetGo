/**
 * Regenerates src/data/exercises.generated.ts from exercises-dataset's data/exercises.json.
 * Takes names, body parts and equipment only: the dataset's media is under a separate licence.
 *   node scripts/import-exercises.js <path to exercises.json>
 */
const fs = require('fs');
const path = require('path');

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/import-exercises.js <path to exercises.json>');
  process.exit(1);
}

const EQUIPMENT = {
  barbell: 'Barbell',
  'ez barbell': 'Barbell',
  'olympic barbell': 'Barbell',
  'trap bar': 'Barbell',
  dumbbell: 'Dumbbell',
  'leverage machine': 'Machine',
  'smith machine': 'Machine',
  'sled machine': 'Machine',
  cable: 'Cable',
  'body weight': 'Bodyweight',
};
const GROUP = {
  chest: 'Chest',
  back: 'Back',
  shoulders: 'Shoulders',
  'upper arms': 'Arms',
  'lower arms': 'Arms',
  'upper legs': 'Legs',
  'lower legs': 'Legs',
  waist: 'Core',
  cardio: 'Cardio',
  neck: 'Other',
};
const SMALL = new Set(['a', 'an', 'and', 'at', 'for', 'from', 'in', 'of', 'on', 'or', 'over', 'the', 'to', 'with']);
const UPPER = new Set(['ez', 'rdl', 'tbs']);

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const titleWord = (word, first) => {
  if (!first && SMALL.has(word)) return word;
  if (UPPER.has(word)) return word.toUpperCase();
  return word.replace(/(^|[-/(])([a-z])/g, (_, lead, ch) => lead + ch.toUpperCase());
};

function cleanName(raw) {
  const name = raw
    .toLowerCase()
    .replace(/\((male|female|(back|side|front) pov)\)/g, ' ')
    .replace(/в°/g, '°')
    .replace(/\bv\.?\s*\d+\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^lever\b/, 'machine')
    .replace(/\blever\b/g, 'machine');
  return name.split(' ').map((w, i) => titleWord(w, i === 0)).join(' ');
}

const catalogSource = fs.readFileSync(path.join(__dirname, '../src/data/catalog.ts'), 'utf8');
const seeded = new Set([...catalogSource.matchAll(/^\s*\['([^']+)',/gm)].map((m) => slug(m[1])));

const rows = JSON.parse(fs.readFileSync(input, 'utf8'));
const seen = new Set();
const out = [];

for (const r of rows) {
  const cardio = r.body_part === 'cardio';
  const equipment = cardio ? 'Cardio' : EQUIPMENT[r.equipment];
  const group = GROUP[r.body_part];
  if (!equipment || !group) continue;

  const name = cleanName(r.name);
  const id = slug(name);
  // "Machine Leg Extension" is the seeded "Leg Extension", so history stays on one exercise.
  if (seeded.has(id) || seeded.has(slug(name.replace(/^Machine /, ''))) || seen.has(id)) continue;
  seen.add(id);

  const split =
    group === 'Chest' || group === 'Shoulders' ? 'push'
    : group === 'Back' ? 'pull'
    : group === 'Legs' ? 'legs'
    : group === 'Arms' ? (r.target === 'triceps' ? 'push' : 'pull')
    : 'other';
  const timed = cardio || /\b(plank|hold|stretch)\b/i.test(name);
  const noWeight = equipment === 'Bodyweight' || cardio;
  out.push([name, group, split, equipment, noWeight, timed ? 'time' : undefined]);
}

out.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

const line = ([name, group, split, equipment, noWeight, mode]) =>
  `  [${JSON.stringify(name)}, '${group}', '${split}', '${equipment}', ${noWeight}${mode ? `, '${mode}'` : ''}],`;

const file = `// Generated by scripts/import-exercises.js. Do not edit by hand.
// Source: github.com/hasaneyldrm/exercises-dataset (MIT, see THIRD_PARTY_NOTICES.md). Names only.
import type { Equipment, MuscleGroup, SetMode, Split } from '../types';

export type ImportedSeed = [name: string, group: MuscleGroup, split: Split, equipment: Equipment, noWeight: boolean, defaultMode?: SetMode];

export const IMPORTED: ImportedSeed[] = [
${out.map(line).join('\n')}
];
`;

fs.writeFileSync(path.join(__dirname, '../src/data/exercises.generated.ts'), file);

const count = (key) => out.reduce((m, r) => ({ ...m, [r[key]]: (m[r[key]] ?? 0) + 1 }), {});
console.log(`records ${rows.length}, kept ${out.length}`);
console.log(count(3), count(1));
